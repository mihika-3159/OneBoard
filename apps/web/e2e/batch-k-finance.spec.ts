import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';
test('founder posts exact journal entries and reconciles a supplied statement',async({page})=>{
  await page.goto('/');
  await page.getByRole('button',{name:/Register/}).click();
  await page.getByPlaceholder('e.g. Alex Founder').fill('Batch K Founder');
  await page.getByPlaceholder('e.g. Apex SaaS Labs').fill('Batch K Workspace');
  await page.getByPlaceholder('founder@example.com').fill(randomUUID()+'@example.test');
  await page.locator('input[type=password]').fill('TestPassword123!');
  await page.getByRole('button',{name:'Create Workspace & Sign In'}).click();
  await expect(page.getByText('Batch K Founder')).toBeVisible();
  await page.getByRole('complementary').locator('nav button').filter({has:page.locator('span').getByText('Finance & Ledger',{exact:true})}).click();
  await expect(page.getByRole('heading',{name:'Accounting journal & reconciliation'})).toBeVisible();
  await page.getByLabel('Accounting month').fill('2020-01');
  await page.getByLabel('Transaction kind').selectOption('opening_cash');
  await page.getByLabel('Amount',{exact:true}).fill('100.30');
  await page.getByLabel('Booking date').fill('2020-01-01');
  await page.getByLabel('Evidence text',{exact:true}).fill('Synthetic opening balance record');
  await page.getByRole('button',{name:'Record transaction'}).click();
  await expect(page.getByText('Journal transaction recorded')).toBeVisible();
  await expect(page.getByText('Journal cash balance:').locator('strong')).toHaveText('100.30');
  await page.getByLabel('Transaction kind').selectOption('expense');
  await page.getByLabel('Amount',{exact:true}).fill('0.10');
  await page.getByLabel('Evidence text',{exact:true}).fill('Synthetic paid expense');
  await page.getByRole('button',{name:'Record transaction'}).click();
  await expect(page.getByText('Journal cash balance:').locator('strong')).toHaveText('100.20');
  await page.getByRole('button',{name:'Bank reconciliation',exact:true}).click();
  await page.getByLabel(/Statement CSV/).fill('reference,date,currency,amount\nfixture-expense,2020-01-01,USD,-0.10\n');
  await page.getByRole('button',{name:'Preview statement'}).click();
  await expect(page.getByText('1 new rows; 0 duplicates.')).toBeVisible();
  await page.getByRole('button',{name:'Confirm statement import'}).click();
  await expect(page.getByText('Statement imported')).toBeVisible();
  await page.getByRole('button',{name:'Find matching journal entries'}).click();
  await page.getByLabel('Journal match for fixture-expense').selectOption({index:1});
  await page.getByRole('button',{name:'Confirm match'}).click();
  await expect(page.getByText('Statement line reconciled')).toBeVisible();
  await page.getByRole('button',{name:'Periods & trends'}).click();
  await page.getByLabel('Close confirmation').fill('CLOSE 2020-01');
  await page.getByRole('button',{name:'Close accounting period'}).click();
  await expect(page.getByText('Accounting period closed')).toBeVisible();
  await expect(page.getByText('Period: Closed',{exact:true})).toBeVisible();
});
